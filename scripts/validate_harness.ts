export const CHECKS: ((h: Harness) => void)[] = [
    checkLabels,
    checkTemplate,
    checkIntake,
    checkPointers,
    checkSuite,
    checkSpecLabels,
    checkChecksDoc,
    checkOpenspec,
    checkTools,
    checkWorkflows,
];

/** Runs the checks over `root` and reports; returns the exit status. */
export function validate(root: string, deps: Deps = realDeps): number {
    const h = new Harness(root, deps);
    for (const check of CHECKS) check(h);
    for (const message of h.warnings) eprint(`WARNING: ${message}`);
    for (const message of h.errors) eprint(`ERROR: ${message}`);
    if (h.errors.length > 0) {
        eprint(
            `validate_harness: ${h.errors.length} error(s). ` +
                "Sources of truth: .github/labels.json, the PR template, the justfile, AGENTS.md.",
        );
        return 1;
    }
    eprint("OK: harness synchronization checks passed.");
    return 0;
}

export function main(argv: string[], root: string = ROOT, deps: Deps = realDeps): number {
    try {
        const args = parseArgs(argv, { boolean: ["help"], alias: { h: "help" } });
        if (args.flags.help) {
            console.log(USAGE);
            return 0;
        }
        if (args.positional.length > 0) throw new UsageError(`unexpected argument ${args.positional[0]}`);
        if (run("git", ["rev-parse", "--show-toplevel"], { cwd: root }).code !== 0) {
            throw new ShapeError("not inside a git checkout");
        }
        return validate(root, deps);
    } catch (error) {
        if (error instanceof UsageError) {
            eprint(`${USAGE}\nvalidate_harness: error: ${error.message}`);
            return 2;
        }
        if (error instanceof ShapeError || error instanceof CommandError) {
            eprint(`validate_harness: error: ${error.message}`);
            return 2;
        }
        throw error;
    }
}

if (import.meta.main) Deno.exit(main(Deno.args));
