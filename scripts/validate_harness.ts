/** A half-open range of 0-based line indexes. */
interface Span {
    start: number;
    end: number;
}

function indentOf(line: string): number {
    return line.length - line.trimStart().length;
}

function isContent(line: string): boolean {
    const trimmed = line.trim();
    return trimmed !== "" && !trimmed.startsWith("#");
}

/** Where a YAML mapping key sits, by its indentation; line numbers only, the values come from the parser. */
function findKey(lines: string[], span: Span, key: string, indent?: number): number {
    const k = escapeRegExp(key);
    const pattern = new RegExp(`^(\\s*)(?:- )?(?:${k}|"${k}"|'${k}')\\s*:(?:\\s|$)`);
    for (let i = span.start; i < span.end; i++) {
        const match = lines[i].match(pattern);
        if (match && (indent === undefined || match[1].length === indent)) return i;
    }
    return -1;
}

/** The lines of the block a key or list item at `line` opens: up to the next content line at its indent or less. */
function blockOf(lines: string[], line: number, limit: number): Span {
    const indent = indentOf(lines[line]);
    for (let i = line + 1; i < limit; i++) {
        if (isContent(lines[i]) && indentOf(lines[i]) <= indent) return { start: line, end: i };
    }
    return { start: line, end: limit };
}

function firstContentAfter(lines: string[], line: number, limit: number): number {
    for (let i = line + 1; i < limit; i++) if (isContent(lines[i])) return i;
    return -1;
}

/** The line span of each step of a `steps:` list inside `parent`; null when the lines do not match the parse. */
function stepSpans(lines: string[], parent: Span, count: number): { steps: number; spans: Span[] } | null {
    const stepsLine = findKey(lines, { start: parent.start + 1, end: parent.end }, "steps");
    if (stepsLine === -1) return null;
    const first = firstContentAfter(lines, stepsLine, parent.end);
    if (first === -1 || !lines[first].trimStart().startsWith("-")) return null;
    const itemIndent = indentOf(lines[first]);
    const starts: number[] = [];
    let end = parent.end;
    for (let i = first; i < parent.end; i++) {
        if (!isContent(lines[i])) continue;
        const indent = indentOf(lines[i]);
        const item = lines[i].trimStart().startsWith("-");
        if (indent < itemIndent || (indent === itemIndent && !item)) {
            end = i;
            break;
        }
        if (indent === itemIndent && item) starts.push(i);
    }
    if (starts.length !== count) return null;
    return {
        steps: stepsLine,
        spans: starts.map((start, i) => ({ start, end: i + 1 < starts.length ? starts[i + 1] : end })),
    };
}

/** The 1-based number of the first non-comment line in `span` that `test` accepts, else `fallback` (0-based). */
function lineWhere(lines: string[], span: Span, test: (line: string) => boolean, fallback: number): number {
    for (let i = span.start; i < span.end; i++) {
        if (!lines[i].trimStart().startsWith("#") && test(lines[i])) return i + 1;
    }
    return fallback + 1;
}

/** The privileged-workflow list of github-checks.md: workflow file name → the privileged triggers it may use. */
export function privilegedList(doc: string): Map<string, Set<string>> {
    const line = doc.match(/^Privileged workflows: (.+)$/m);
    if (!line) throw new ShapeError(`${CHECKS_DOC} has no line 'Privileged workflows: ...'`);
    const listed = new Map<string, Set<string>>();
    for (const entry of line[1].matchAll(/`([^`]+\.yml)` \(([^)]*)\)/g)) {
        const triggers = [...entry[2].matchAll(/`([^`]+)`/g)].map((m) => m[1]);
        listed.set(entry[1], new Set([...(listed.get(entry[1]) ?? []), ...triggers]));
    }
    if (listed.size === 0) {
        throw new ShapeError(`${CHECKS_DOC}: the 'Privileged workflows:' line names no \`file.yml\` (\`trigger\`)`);
    }
    return listed;
}

/** The trigger names of a workflow's `on:` value. */
export function triggersOf(on: unknown): string[] {
    if (typeof on === "string") return [on];
    if (Array.isArray(on)) return on.map((t) => String(t));
    if (isRecord(on)) return Object.keys(on);
    return [];
}

/** The scopes a `permissions:` value grants write access to (`write-all` → ["*"]). */
export function writeGrants(permissions: unknown): string[] {
    if (permissions === "write-all") return ["*"];
    if (!isRecord(permissions)) return [];
    return Object.entries(permissions).filter(([, v]) => v === "write").map(([k]) => k);
}

const EVENT_EXPRESSION = /\$\{\{([\s\S]*?)\}\}/g;
const UNTRUSTED_CONTEXT = /\bgithub\s*\.\s*(?:event(?=\s*[.[])|head_ref\b)/;

/** The `${{ ... }}` expressions in a string that read the event payload or the head ref. */
export function eventExpressions(text: string): string[] {
    return [...text.matchAll(EVENT_EXPRESSION)].filter((m) => UNTRUSTED_CONTEXT.test(m[1])).map((m) => m[0]);
}

const PR_CONTENT: RegExp[] = [
    /refs\/pull\//,
    /\bgh\s+pr\s+checkout\b/,
    /\bmerge_commit_sha\b/,
    /\bhead\.(?:sha|ref)\b/,
    /\bhead_ref\b/,
    /\bgit\s+fetch\b.*\b(?:head|refs\/pull)\b/,
];

/** The first pull-request-content pattern a string matches, or null. */
export function prContent(text: string): RegExp | null {
    return PR_CONTENT.find((p) => p.test(text)) ?? null;
}

function stringsIn(node: unknown, out: string[]): string[] {
    if (typeof node === "string") out.push(node);
    else if (Array.isArray(node)) node.forEach((n) => stringsIn(n, out));
    else if (isRecord(node)) Object.values(node).forEach((n) => stringsIn(n, out));
    return out;
}

const PINNED = /^[^@\s]+@[0-9a-f]{40}$/;
const VERSION_COMMENT = /#\s*v\d/;
const SCRIPT_PATH = /(?:^|[\s"'=;&|(])(?:\.\/)?((?:[\w.-]+\/)*[\w.-]+\.ts)(?=$|[\s"';&|)])/gm;
const REMOTE_RUN = /\bdeno\b[^\n]*?\s["']?(?:npm:|jsr:|https?:\/\/)/;

function isCheckout(uses: string): boolean {
    return uses === "actions/checkout" || uses.startsWith("actions/checkout@");
}

/** A problem found while following a script's imports. */
export interface ImportProblem {
    file: string;
    specifier: string;
    kind: "remote" | "missing" | "dynamic";
}

/** Every import specifier in TypeScript source; a dynamic import of a computed value is returned as null. */
export function importSpecifiers(source: string): (string | null)[] {
    const code = source.replace(/^\s*\/\*[\s\S]*?\*\//gm, "").replace(/^\s*\/\/.*$/gm, "");
    const specifiers: (string | null)[] = [];
    for (const m of code.matchAll(/^\s*(?:import|export)\b[^'"`;]*?\bfrom\s*(['"])([^'"]+)\1/gm)) specifiers.push(m[2]);
    for (const m of code.matchAll(/^\s*import\s*(['"])([^'"]+)\1/gm)) specifiers.push(m[2]);
    for (const m of code.matchAll(/\bimport\s*\(\s*(?:(['"])([^'"]+)\1)?/g)) specifiers.push(m[2] ?? null);
    return specifiers;
}

/** Follows a script's local imports and reports every remote, missing, or computed one (paths repo-relative). */
export function importProblems(h: Harness, entry: string): ImportProblem[] {
    const problems: ImportProblem[] = [];
    const seen = new Set<string>();
    const visit = (file: string) => {
        if (seen.has(file)) return;
        seen.add(file);
        if (!h.isFile(file)) {
            problems.push({ file, specifier: file, kind: "missing" });
            return;
        }
        if (!/\.(?:ts|tsx|js|mjs)$/.test(file)) return;
        for (const specifier of importSpecifiers(h.read(file))) {
            if (specifier === null) problems.push({ file, specifier: "import(<computed>)", kind: "dynamic" });
            else if (specifier.startsWith("./") || specifier.startsWith("../")) {
                visit(normalize(`${dirname(file)}/${specifier}`));
            } else problems.push({ file, specifier, kind: "remote" });
        }
    };
    visit(normalize(entry));
    return problems;
}

/** The repository-relative `.ts` scripts a `run:` text executes. */
export function scriptsRun(text: string): string[] {
    return [...new Set([...text.matchAll(SCRIPT_PATH)].map((m) => normalize(m[1])))];
}

interface StepContext {
    file: string;
    lines: string[];
    step: Record<string, unknown>;
    span: Span;
    fallback: number;
}

/** Rules every step obeys, in a workflow job or a composite action. */
function checkStep(h: Harness, s: StepContext): void {
    const { file, lines, step, span, fallback } = s;
    const usesLine = lineWhere(lines, span, (l) => /^\s*(?:- )?uses\s*:/.test(l), fallback);
    if (typeof step.uses === "string" && !step.uses.startsWith("./")) {
        if (!PINNED.test(step.uses)) {
            h.error(`${file}:${usesLine}: \`${step.uses}\` is not pinned to a 40-character commit SHA; pin it.`);
        } else if (!VERSION_COMMENT.test(lines[usesLine - 1].replace(/^.*?uses\s*:/, ""))) {
            h.error(`${file}:${usesLine}: pinned action lacks a version comment; add \`# v<version>\` after it.`);
        }
    }
    const inputs = isRecord(step.with) ? step.with : {};
    if (typeof step.uses === "string" && isCheckout(step.uses)) {
        const persist = inputs["persist-credentials"];
        if (persist !== false && persist !== "false") {
            h.error(
                `${file}:${usesLine}: actions/checkout without \`persist-credentials: false\`; add it so the token ` +
                    "stays out of the runner's git config.",
            );
        }
    }
    for (const [where, value] of [["a `run:` line", step.run], ["a `script:` input", inputs.script]] as const) {
        if (typeof value !== "string") continue;
        for (const expression of eventExpressions(value)) {
            const line = lineWhere(lines, span, (l) => l.includes(expression), fallback);
            h.error(
                `${file}:${line}: \`${expression}\` reaches ${where}; pass it through \`env:\` and quote the variable.`,
            );
        }
    }
}

/** Rules for a job of a workflow with a privileged trigger. */
function checkPrivilegedStep(h: Harness, s: StepContext, job: string): void {
    const { file, lines, step, span, fallback } = s;
    const usesLine = lineWhere(lines, span, (l) => /^\s*(?:- )?uses\s*:/.test(l), fallback);
    const inputs = isRecord(step.with) ? step.with : {};
    const skip = new Set<unknown>();
    if (typeof step.uses === "string") {
        if (isCheckout(step.uses)) {
            for (const input of ["ref", "repository"]) {
                if (inputs[input] === undefined) continue;
                skip.add(inputs[input]);
                h.error(
                    `${file}:${lineWhere(lines, span, (l) => new RegExp(`^\\s*${input}\\s*:`).test(l), fallback)}: ` +
                        `job ${quote(job)} checks out with \`${input}:\` under a privileged trigger; check out the ` +
                        `default (base) commit only and read the head through the REST API (see ${CHECKS_DOC}).`,
                );
            }
        } else if (step.uses === SETUP_TOOLS) {
            const asked = Object.keys(inputs);
            if (asked.length > 0) {
                h.error(
                    `${file}:${usesLine}: job ${quote(job)} passes ${asked.map((i) => `\`${i}\``).join(", ")} to ` +
                        `${SETUP_TOOLS} under a privileged trigger; a job holding a write token installs Deno only.`,
                );
            }
        } else {
            h.error(
                `${file}:${usesLine}: job ${quote(job)} uses \`${step.uses}\` under a privileged trigger; only ` +
                    `actions/checkout and ${SETUP_TOOLS} may run beside its token.`,
            );
        }
    }
    for (const value of stringsIn(step, [])) {
        if (skip.has(value)) continue;
        const pattern = prContent(value);
        if (pattern) {
            h.error(
                `${file}:${lineWhere(lines, span, (l) => pattern.test(l), fallback)}: job ${quote(job)} reaches pull ` +
                    `request content (\`${pattern.source}\`) under a privileged trigger; read the head through the ` +
                    `REST API instead (see ${CHECKS_DOC}).`,
            );
        }
    }
    if (typeof step.run !== "string") return;
    if (REMOTE_RUN.test(step.run)) {
        h.error(
            `${file}:${lineWhere(lines, span, (l) => REMOTE_RUN.test(l), fallback)}: job ${quote(job)} runs a remote ` +
                "module through deno beside its token; run a local script that imports only local modules.",
        );
    }
    for (const script of scriptsRun(step.run)) {
        const line = lineWhere(lines, span, (l) => l.includes(script), fallback);
        for (const problem of importProblems(h, script)) {
            const detail = problem.kind === "missing"
                ? `${problem.file}, which does not exist`
                : `${script}, whose ${problem.file} has ${
                    problem.kind === "remote" ? "the remote import" : "the computed import"
                } \`${problem.specifier}\``;
            h.error(
                `${file}:${line}: job ${quote(job)} runs ${detail}; a script beside a write token imports only ` +
                    "local modules, transitively (no lockfile pins a remote one).",
            );
        }
    }
}

function checkWorkflowFile(h: Harness, file: string, privileged: Map<string, Set<string>>): void {
    const text = h.read(file);
    const lines = text.split("\n");
    const doc = h.yaml(file);
    if (!isRecord(doc)) throw new ShapeError(`${file} is not a YAML mapping`);
    const top: Span = { start: 0, end: lines.length };
    const name = basename(file);

    if (doc.permissions === undefined || doc.permissions === null) {
        h.error(`${file}:1: no top-level \`permissions:\`; add \`permissions: {}\` and job-level grants.`);
    }
    const triggers = triggersOf(doc.on);
    const onLine = findKey(lines, top, "on", 0);
    const onSpan = onLine === -1 ? top : blockOf(lines, onLine, lines.length);
    const triggerLine = (trigger: string) =>
        lineWhere(lines, onSpan, (l) => new RegExp(`(?:^|[\\s\\[,-])${trigger}\\b`).test(l), Math.max(onLine, 0));
    if (triggers.includes("workflow_run")) {
        h.error(
            `${file}:${triggerLine("workflow_run")}: \`workflow_run\` is forbidden; it runs with a write token on ` +
                "the result of an untrusted run. Use the triggering workflow's own events.",
        );
    }
    const isPrivileged = triggers.some((t) => PRIVILEGED_TRIGGERS.includes(t));
    for (const trigger of triggers.filter((t) => PRIVILEGED_TRIGGERS.includes(t))) {
        if (!privileged.get(name)?.has(trigger)) {
            h.error(
                `${file}:${triggerLine(trigger)}: uses \`${trigger}\` but ${CHECKS_DOC} does not list it with that ` +
                    "trigger on its 'Privileged workflows:' line; add it there with the reason, or use another event.",
            );
        }
    }
    const isPullRequest = triggers.includes("pull_request");
    const reportWrites = (permissions: unknown, span: Span, where: string) => {
        if (!isPullRequest) return;
        for (const scope of writeGrants(permissions)) {
            const line = lineWhere(
                lines,
                span,
                (l) => scope === "*" ? /write-all/.test(l) : new RegExp(`^\\s*${escapeRegExp(scope)}\\s*:`).test(l),
                span.start,
            );
            h.error(
                `${file}:${line}: ${where} grants \`${scope === "*" ? "write-all" : `${scope}: write`}\` in a ` +
                    "`pull_request` workflow; grant read access only, and move the write to a privileged workflow.",
            );
        }
    };
    const topPermissions = findKey(lines, top, "permissions", 0);
    if (topPermissions !== -1) {
        reportWrites(doc.permissions, blockOf(lines, topPermissions, lines.length), "the workflow");
    }

    const jobsLine = findKey(lines, top, "jobs", 0);
    if (!isRecord(doc.jobs) || jobsLine === -1) {
        h.error(`${file}: no \`jobs:\` section.`);
        return;
    }
    const jobsSpan = blockOf(lines, jobsLine, lines.length);
    const jobIndentLine = firstContentAfter(lines, jobsLine, jobsSpan.end);
    const jobIndent = jobIndentLine === -1 ? 2 : indentOf(lines[jobIndentLine]);
    for (const [id, value] of Object.entries(doc.jobs)) {
        const job = isRecord(value) ? value : {};
        const jobLine = findKey(lines, { start: jobsLine + 1, end: jobsSpan.end }, id, jobIndent);
        const jobSpan = jobLine === -1 ? jobsSpan : blockOf(lines, jobLine, jobsSpan.end);
        const at = jobLine === -1 ? jobsLine : jobLine;
        if (job.permissions === undefined || job.permissions === null) {
            h.error(`${file}:${at + 1}: job ${quote(id)} declares no \`permissions:\`; add the grants it needs.`);
        } else {
            const permissionsLine = findKey(lines, { start: jobSpan.start + 1, end: jobSpan.end }, "permissions");
            reportWrites(
                job.permissions,
                permissionsLine === -1 ? jobSpan : blockOf(lines, permissionsLine, jobSpan.end),
                `job ${quote(id)}`,
            );
        }
        if (typeof job.uses === "string") {
            // A reusable-workflow call: no steps and no timeout of its own, but the reference is pinned like an action.
            checkStep(h, { file, lines, step: { uses: job.uses }, span: jobSpan, fallback: at });
            if (isPrivileged) {
                h.error(
                    `${file}:${at + 1}: job ${quote(id)} calls the reusable workflow \`${job.uses}\` under a ` +
                        `privileged trigger; only actions/checkout and ${SETUP_TOOLS} may run beside its token.`,
                );
            }
            continue;
        }
        if (job["timeout-minutes"] === undefined || job["timeout-minutes"] === null) {
            h.error(`${file}:${at + 1}: job ${quote(id)} sets no \`timeout-minutes\`; add one so a hung run stops.`);
        }
        const steps = Array.isArray(job.steps) ? job.steps : [];
        const located = jobLine === -1 ? null : stepSpans(lines, jobSpan, steps.length);
        steps.forEach((value, index) => {
            const step = isRecord(value) ? value : {};
            const span = located ? located.spans[index] : jobSpan;
            const fallback = located ? located.spans[index].start : at;
            checkStep(h, { file, lines, step, span, fallback });
            if (isPrivileged) checkPrivilegedStep(h, { file, lines, step, span, fallback }, id);
        });
        if (isPrivileged) {
            // Job-level values (`env`, `if`, `container`) beside the steps.
            const { steps: _steps, ...rest } = job;
            for (const value of stringsIn(rest, [])) {
                const pattern = prContent(value);
                if (pattern) {
                    h.error(
                        `${file}:${lineWhere(lines, jobSpan, (l) => pattern.test(l), at)}: job ${quote(id)} reaches ` +
                            `pull request content (\`${pattern.source}\`) under a privileged trigger; read the head ` +
                            `through the REST API instead (see ${CHECKS_DOC}).`,
                    );
                }
            }
        }
    }
}

function checkActionFile(h: Harness, file: string): void {
    const lines = h.read(file).split("\n");
    const doc = h.yaml(file);
    if (!isRecord(doc)) throw new ShapeError(`${file} is not a YAML mapping`);
    const runs = isRecord(doc.runs) ? doc.runs : {};
    const steps = Array.isArray(runs.steps) ? runs.steps : [];
    const runsLine = findKey(lines, { start: 0, end: lines.length }, "runs", 0);
    const runsSpan = runsLine === -1 ? { start: 0, end: lines.length } : blockOf(lines, runsLine, lines.length);
    const located = runsLine === -1 ? null : stepSpans(lines, runsSpan, steps.length);
    steps.forEach((value, index) => {
        const step = isRecord(value) ? value : {};
        const span = located ? located.spans[index] : runsSpan;
        checkStep(h, { file, lines, step, span, fallback: span.start });
    });
}

export function checkWorkflows(h: Harness): void {
    const privileged = privilegedList(h.read(CHECKS_DOC));
    for (const workflow of workflowFiles(h)) checkWorkflowFile(h, workflow, privileged);
    for (const action of h.list(ACTIONS)) {
        const file = `${ACTIONS}/${action}/action.yml`;
        if (h.isFile(file)) checkActionFile(h, file);
    }
}

