/** A required file or command is unreadable or not in the shape a check reads; main() exits 2. */
export class ShapeError extends Error {}

/** The interfaces a check reaches outside the file system; tests replace them. */
export interface Deps {
    /** The label taxonomy scripts/spec_changes.ts declares, in the shape `labels --taxonomy` prints. */
    taxonomy(root: string): unknown;
    /** Repository-relative paths of the tracked files. */
    trackedFiles(root: string): string[];
    /** The tracked text files' lines (working-tree content) matching an extended regular expression. */
    grepTracked(root: string, pattern: string): { file: string; line: number }[];
}

export const realDeps: Deps = {
    taxonomy() {
        return { managed: [...MANAGED_LABELS] };
    },
    trackedFiles(root) {
        return runChecked("git", ["ls-files", "-z"], { cwd: root }).split("\0").filter((p) => p !== "");
    },
    grepTracked(root, pattern) {
        // One process instead of reading every file: `-z` prints `file\0line\0text`, `-I` skips binary files.
        const args = ["grep", "-z", "-n", "-I", "-E", "-e", pattern, "--", "."];
        const out = run("git", args, { cwd: root });
        if (out.code === 1 && out.stderr.trim() === "") return [];
        if (out.code !== 0) {
            throw new CommandError(`\`git ${args.join(" ")}\` exited ${out.code}: ${out.stderr.trim()}`);
        }
        return out.stdout.split("\n").filter((l) => l !== "").map((entry) => {
            const [file, line] = entry.split("\0");
            const number = Number(line);
            if (file === undefined || !Number.isInteger(number)) {
                throw new CommandError(
                    `\`git ${args.join(" ")}\` printed an unexpected line: ${JSON.stringify(entry)}`,
                );
            }
            return { file, line: number };
        });
    },
};

/** One validation run over a repository root: the findings and the file access the checks share. */
export class Harness {
    readonly errors: string[] = [];
    readonly warnings: string[] = [];
    constructor(readonly root: string, readonly deps: Deps = realDeps) {}

    path(relative: string): string {
        return join(this.root, relative);
    }
    rel(path: string): string {
        return path.startsWith(this.root + "/") ? path.slice(this.root.length + 1) : path;
    }
    /** Reads a repository-relative file; an unreadable one stops the run with exit 2. */
    read(relative: string): string {
        try {
            return Deno.readTextFileSync(this.path(relative));
        } catch (error) {
            throw new ShapeError(`cannot read ${relative}: ${(error as Error).message}`);
        }
    }
    /** Reads and parses a repository-relative YAML file. */
    yaml(relative: string): unknown {
        const text = this.read(relative);
        try {
            return parseYaml(text);
        } catch (error) {
            throw new ShapeError(`${relative} is not valid YAML: ${(error as Error).message}`);
        }
    }
    exists(relative: string): boolean {
        return statOrNull(this.path(relative)) !== null;
    }
    isDir(relative: string): boolean {
        return statOrNull(this.path(relative))?.isDirectory ?? false;
    }
    isFile(relative: string): boolean {
        return statOrNull(this.path(relative))?.isFile ?? false;
    }
    /** Sorted names of the entries of a directory (empty when it does not exist). */
    list(relative: string): string[] {
        if (!this.isDir(relative)) return [];
        return [...Deno.readDirSync(this.path(relative))].map((e) => e.name).sort();
    }
    error(message: string): void {
        this.errors.push(message);
    }
    warn(message: string): void {
        this.warnings.push(message);
    }
}

function statOrNull(path: string): Deno.FileInfo | null {
    try {
        return Deno.statSync(path);
    } catch (error) {
        if (error instanceof Deno.errors.NotFound || error instanceof Deno.errors.NotADirectory) return null;
        throw error;
    }
}

