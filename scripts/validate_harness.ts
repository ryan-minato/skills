#!/usr/bin/env -S deno run --no-prompt --allow-read=. --allow-run=git
// Validates the repository harness's synchronization points and the security shape of its workflows.
//
// Every check is a pair of files that must agree, or a rule over files, that nothing else enforces; a
// finding names the file (and line, where there is one) to edit. YAML is read with @std/yaml; Markdown,
// the justfile, and shell text inside a workflow's `run:` are read as text.
//
// Checks (errors unless marked warning):
//   labels     issue forms and dependabot reference only labels in .github/labels.json; every label has an
//              applier; catalog/* labels, the catalogs on disk, and every form's Catalog options agree;
//              priority/* labels and every form's Priority options agree
//   template   the PR template carries the related / changes / validation / checklist headings, the security
//              checklist line, and a `Spec:` line
//   intake     ISSUE_TEMPLATE/config.yml disables blank issues
//   pointers   every path AGENTS.md and ARCHITECTURE.md name exists; every .agents/knowledge/*.md is named in
//              AGENTS.md; every `just <recipe>` AGENTS.md names exists (README: warning)
//   suite      every skills/engineering/brownfield-* member carries the `## Evidence discipline` section of its
//              SKILL.md byte-identical to brownfield-investigation's, the source
//   spec       the spec/* labels are exactly the managed labels scripts/spec_changes.ts exports
//              (MANAGED_LABELS), each applied by a workflow, and spec-labels.yml's literal `case` list
//              admits the same set
//   checks     workflow job names and the table in .agents/knowledge/github-checks.md agree both ways
//   openspec   .agents/skills/openspec-* is exactly the core skill set, each generated by the version the
//              justfile pins; the target marker is `agents`; checks.yml and devcontainer.json name no
//              OpenSpec or OpenTofu version; openspec/config.yaml selects the project schema, whose
//              templates exist, and carries no `rules:`
//   tools      no tracked file but the justfile names an OpenSpec version (`@fission-ai/openspec@<digit>`);
//              no deno.lock is tracked
//   workflows  over .github/workflows/*.yml and .github/actions/*/action.yml: permissions top-level and per
//              job; every external action pinned to a 40-hex commit SHA with a `# v<version>` comment on its
//              line; every actions/checkout sets `persist-credentials: false`; every job sets
//              `timeout-minutes`; no `${{ github.event.* }}` or `${{ github.head_ref }}` in a `run:` or a
//              `with.script` input; the privileged triggers (pull_request_target, issue_comment, issues)
//              only in the workflows github-checks.md's "Privileged workflows:" line lists with that
//              trigger, whose jobs never check out, fetch, or run pull request content, use no action but
//              actions/checkout and ./.github/actions/setup-tools (with no inputs), and run only scripts
//              whose imports are local, transitively; no `workflow_run`; no `pull_request` workflow grants
//              a write permission
// `checkBudget` (AGENTS.md line budget, Markdown table width) is exported and tested but not run by main()
// yet; the knowledge rebuild turns it on.
//
// Usage: ./scripts/validate_harness.ts   (from the repository root)
// Called by: `just validate` (hence `just check` and CI) and the validate-harness pre-commit hook.
// Output: findings and the verdict on stderr; nothing on stdout.
// Exit codes: 0 all checks pass (warnings allowed); 1 at least one error; 2 usage error, or a required file
// or command is unreadable or not in the expected shape.
