/** A string quoted as Python's repr() quotes it. */
export function quote(value: string): string {
    if (value.includes("'") && !value.includes('"')) return `"${value}"`;
    return `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

/** A list of strings written as Python writes one. */
export function quoteList(values: Iterable<string>): string {
    return `[${[...values].map(quote).join(", ")}]`;
}

function sorted(values: Iterable<string>): string[] {
    return [...values].sort();
}

function isRecord(value: unknown): value is Record<string, unknown> {
    return typeof value === "object" && value !== null && !Array.isArray(value);
}

function setEquals(a: Set<string>, b: Set<string>): boolean {
    return a.size === b.size && [...a].every((v) => b.has(v));
}

function escapeRegExp(text: string): string {
    return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// --- labels ------------------------------------------------------------------------------------------

function formLabels(doc: unknown): string[] {
    if (!isRecord(doc)) return [];
    const labels = doc.labels;
    if (Array.isArray(labels)) return labels.map((l) => String(l));
    if (typeof labels === "string") return [labels];
    return [];
}

/** Options of the form element whose `attributes.label` equals `label`; null when there is none. */
export function formDropdownOptions(doc: unknown, label: string): string[] | null {
    const body = isRecord(doc) && Array.isArray(doc.body) ? doc.body : [];
    for (const element of body) {
        const attributes = isRecord(element) && isRecord(element.attributes) ? element.attributes : null;
        if (attributes && attributes.label === label) {
            return Array.isArray(attributes.options) ? attributes.options.map((o) => String(o)) : [];
        }
    }
    return null;
}

function dependabotLabels(doc: unknown): Set<string> {
    const labels = new Set<string>();
    const updates = isRecord(doc) && Array.isArray(doc.updates) ? doc.updates : [];
    for (const update of updates) {
        if (isRecord(update) && Array.isArray(update.labels)) {
            for (const label of update.labels) labels.add(String(label));
        }
    }
    return labels;
}

function readLabels(h: Harness): unknown[] {
    let data: unknown;
    try {
        data = JSON.parse(h.read(LABELS));
    } catch (error) {
        if (error instanceof ShapeError) throw error;
        throw new ShapeError(`${LABELS} is not valid JSON: ${(error as Error).message}`);
    }
    if (!Array.isArray(data)) throw new ShapeError(`${LABELS} must be a JSON list of label objects`);
    return data;
}

export function checkLabels(h: Harness): void {
    const labels = new Map<string, unknown>();
    for (const item of readLabels(h)) {
        const record = isRecord(item) ? item : {};
        const name = String(record.name ?? "").trim();
        const applier = record.applied_by;
        if (typeof applier !== "string" || !APPLIERS.includes(applier)) {
            h.error(`${LABELS}: label ${quote(name)} needs "applied_by" set to one of ${quoteList(APPLIERS)}.`);
        }
        // Only the spec status axes are applied by a workflow; anywhere else the value would claim an
        // automation this repository does not run.
        if (applier === "workflow" && !name.startsWith("spec/")) {
            h.error(`${LABELS}: label ${quote(name)} may not claim "applied_by": "workflow" outside the spec/ prefix.`);
        }
        labels.set(name, applier);
    }

    const formLabelSet = new Set<string>();
    const catalogOptions = new Map<string, string[]>();
    const priorityOptions = new Map<string, string[]>();
    for (const name of h.list(FORMS_DIR)) {
        if (!name.endsWith(".yml") || name === "config.yml") continue;
        const form = `${FORMS_DIR}/${name}`;
        const doc = h.yaml(form);
        for (const label of formLabels(doc)) formLabelSet.add(label);
        for (const [key, store] of [["Catalog", catalogOptions], ["Priority", priorityOptions]] as const) {
            const options = formDropdownOptions(doc, key);
            if (options === null) {
                h.error(`${form}: no dropdown labelled ${quote(key)}; the triage script reads that section.`);
            } else {
                store.set(form, options);
            }
        }
    }
    const depLabels = h.exists(DEPENDABOT) ? dependabotLabels(h.yaml(DEPENDABOT)) : new Set<string>();
    const referenced = new Set([...formLabelSet, ...depLabels]);

    for (const label of sorted(referenced)) {
        if (!labels.has(label)) {
            h.error(
                `label ${quote(label)} is referenced by an issue form or dependabot.yml but missing from ${LABELS}; ` +
                    "GitHub would drop it silently.",
            );
        }
    }
    for (const [name, applier] of labels) {
        const managed = MANAGED_PREFIXES.some((p) => name.startsWith(p));
        const consumed = referenced.has(name) || managed || name === NEEDS_TRIAGE || applier === "human" ||
            applier === "workflow";
        if (!consumed) {
            h.error(
                `${LABELS}: label ${quote(name)} is applied by nothing ` +
                    "(no form, dependabot, triage prefix, or applied_by human).",
            );
        }
        if (applier === "form" && !referenced.has(name)) {
            h.error(`${LABELS}: label ${quote(name)} says applied_by form but no form applies it.`);
        }
        if (applier === "triage" && !managed) {
            h.error(`${LABELS}: label ${quote(name)} says applied_by triage but has no managed prefix.`);
        }
        if (applier === "workflow" && !name.startsWith("spec/")) {
            h.error(`${LABELS}: label ${quote(name)} says applied_by workflow; only spec/* labels are workflow-owned.`);
        }
    }

    const catalogsOnDisk = new Set(h.list("skills").filter((n) => h.isDir(`skills/${n}`)));
    const catalogLabels = new Set(
        [...labels.keys()].filter((n) => n.startsWith("catalog/")).map((n) => n.slice("catalog/".length)),
    );
    catalogLabels.delete("repository");
    if (!setEquals(catalogLabels, catalogsOnDisk)) {
        h.error(
            `catalog/* labels in ${LABELS} (${quoteList(sorted(catalogLabels))}) differ from the catalogs ` +
                `under skills/ (${quoteList(sorted(catalogsOnDisk))}).`,
        );
    }
    for (const [form, options] of catalogOptions) {
        const withoutRepository = new Set(options.filter((o) => o !== "repository"));
        if (!setEquals(withoutRepository, catalogsOnDisk) || !options.includes("repository")) {
            h.error(
                `${form}: Catalog options ${quoteList(options)} must be the catalogs under skills/ plus 'repository'.`,
            );
        }
    }
    const priorityLabels = new Set(
        [...labels.keys()].filter((n) => n.startsWith("priority/")).map((n) => n.slice("priority/".length)),
    );
    for (const [form, options] of priorityOptions) {
        if (!setEquals(new Set(options), priorityLabels)) {
            h.error(
                `${form}: Priority options ${quoteList(options)} differ from priority/* labels ` +
                    `${quoteList(sorted(priorityLabels))}.`,
            );
        }
    }
}

// --- template, intake --------------------------------------------------------------------------------

export function checkTemplate(h: Harness): void {
    const text = h.read(PR_TEMPLATE).replace(/<!--[\s\S]*?-->/g, "");
    const headings = [...text.matchAll(/^## (.+?)\s*$/gm)].map((m) => m[1].toLowerCase());
    for (const role of ["related", "changes", "validation", "checklist"]) {
        if (!headings.some((heading) => heading.includes(role))) {
            h.error(`${PR_TEMPLATE}: no '## ' heading contains ${quote(role)}; scripts/check_pr_policy.ts needs one.`);
        }
    }
    if (!/^\s*- \[ \].*secrets/im.test(text)) {
        h.error(
            `${PR_TEMPLATE}: the checklist needs an unticked line containing 'secrets' ` +
                "(check_pr_policy.ts keys on it).",
        );
    }
    if (!/^Spec:/m.test(text)) {
        h.error(`${PR_TEMPLATE}: needs a 'Spec:' line (see .agents/knowledge/spec-workflow.md).`);
    }
}

export function checkIntake(h: Harness): void {
    const config = `${FORMS_DIR}/config.yml`;
    const doc = h.yaml(config);
    if (!isRecord(doc) || doc.blank_issues_enabled !== false) {
        h.error(`${config}: blank_issues_enabled must be false (questions route to Discussions).`);
    }
}

// --- pointers ----------------------------------------------------------------------------------------

export function pathLike(name: string): boolean {
    if ([..."<>*{} \"'"].some((ch) => name.includes(ch)) || LABEL_PREFIX_SKIP.some((p) => name.startsWith(p))) {
        return false;
    }
    if (/^[A-Z/]+$/.test(name)) return false;
    return name.includes("/") || name.startsWith(".");
}

function walkMarkdown(h: Harness, dir: string): string[] {
    const found: string[] = [];
    for (const name of h.list(dir)) {
        const path = `${dir}/${name}`;
        if (h.isDir(path)) found.push(...walkMarkdown(h, path));
        else if (name.endsWith(".md")) found.push(path);
    }
    return found;
}

export function justRecipes(justfile: string): Set<string> {
    return new Set([...justfile.matchAll(/^([a-z][a-z0-9-]*)(?:\s+\+?[A-Z_]+)*\s*:(?!=)/gm)].map((m) => m[1]));
}

export function checkPointers(h: Harness): void {
    for (const doc of [AGENTS_MD, ARCHITECTURE_MD]) {
        const tokens = sorted(new Set([...h.read(doc).matchAll(/`([^`\n]+)`/g)].map((m) => m[1])));
        for (const token of tokens) {
            if (!pathLike(token)) continue;
            const candidate = token.replace(/\/+$/, "").split(":")[0];
            if (candidate.startsWith("../")) continue;
            if (!h.exists(candidate) && !h.exists(`skills/${candidate}`)) {
                h.error(`${doc} names \`${token}\`, which does not exist.`);
            }
        }
    }
    const agents = h.read(AGENTS_MD);
    for (const knowledge of sorted(walkMarkdown(h, KNOWLEDGE))) {
        if (!agents.includes(knowledge)) {
            h.error(`${knowledge} is not named in AGENTS.md; a knowledge file without a pointer is invisible.`);
        }
    }
    const recipes = justRecipes(h.read(JUSTFILE));
    for (const [doc, report] of [[AGENTS_MD, "error"], [README_MD, "warn"]] as const) {
        const named = sorted(new Set([...h.read(doc).matchAll(/`just ([a-z][a-z0-9-]*)/g)].map((m) => m[1])));
        for (const recipe of named) {
            if (!recipes.has(recipe)) {
                const message = `${doc} names \`just ${recipe}\`, which is not a justfile recipe.`;
                if (report === "error") h.error(message);
                else h.warn(message);
            }
        }
    }
}

// --- suite -------------------------------------------------------------------------------------------

/** One level-2 section, heading included, up to the next level-2 heading, untrimmed; null when absent. */
export function markdownSection(text: string, heading: string): string | null {
    const pattern = new RegExp(`^${escapeRegExp(heading)}[ \\t]*$[\\s\\S]*?(?=^## (?!#)|(?![\\s\\S]))`, "m");
    const match = text.match(pattern);
    return match ? match[0] : null;
}

export function checkSuite(h: Harness): void {
    const members = h.list(ENGINEERING)
        .filter((name) => name.startsWith(SUITE_PREFIX) && h.isDir(`${ENGINEERING}/${name}`))
        .map((name) => `${ENGINEERING}/${name}/SKILL.md`)
        .sort();
    if (members.length === 0) return;
    if (!h.isFile(SUITE_SOURCE)) {
        h.error(
            `${SUITE_SOURCE} is missing while other brownfield suite members exist; it is the source of the ` +
                `shared \`${SUITE_HEADING}\` section. Restore it before adding or keeping other members.`,
        );
        return;
    }
    const source = markdownSection(h.read(SUITE_SOURCE), SUITE_HEADING);
    if (source === null) {
        h.error(`${SUITE_SOURCE} has no \`${SUITE_HEADING}\` section; the suite's shared section starts there.`);
        return;
    }
    for (const member of members) {
        if (member === SUITE_SOURCE) continue;
        if (!h.isFile(member)) {
            h.error(`${member} is missing; every brownfield suite member needs a SKILL.md.`);
            continue;
        }
        const section = markdownSection(h.read(member), SUITE_HEADING);
        if (section === null) {
            h.error(`${member} has no \`${SUITE_HEADING}\` section; copy it from ${SUITE_SOURCE}.`);
        } else if (section !== source) {
            h.error(
                `${member}: the \`${SUITE_HEADING}\` section differs from ${SUITE_SOURCE}. Edit the source ` +
                    "first, then copy its section over this one (all five members share it byte for byte).",
            );
        }
    }
}

// --- spec labels -------------------------------------------------------------------------------------

/** Every `run:` string of a workflow document, in job and step order. */
function runScripts(doc: unknown): string[] {
    const scripts: string[] = [];
    const jobs = isRecord(doc) && isRecord(doc.jobs) ? doc.jobs : {};
    for (const job of Object.values(jobs)) {
        const steps = isRecord(job) && Array.isArray(job.steps) ? job.steps : [];
        for (const step of steps) {
            if (isRecord(step) && typeof step.run === "string") scripts.push(step.run);
        }
    }
    return scripts;
}

/** The literal `case` pattern list in spec-labels.yml's steps that names the labels it may apply. */
export function labelsCaseLine(doc: unknown): string {
    for (const script of runScripts(doc)) {
        const match = script.match(/^\s*(spec\/[a-z-]+(?:\|spec\/[a-z-]+)*\)).*$/m);
        if (match) return match[1];
    }
    throw new ShapeError(`${SPEC_LABELS_WORKFLOW} has no literal \`case\` list of the labels it may apply.`);
}

export function checkSpecLabels(h: Harness): void {
    const taxonomy = h.deps.taxonomy(h.root);
    if (!isRecord(taxonomy) || !Array.isArray(taxonomy.managed)) {
        throw new ShapeError("the spec_changes.ts taxonomy has no managed list");
    }
    const managed = new Set(taxonomy.managed.map((l) => String(l)));
    const labels = new Map<string, unknown>();
    for (const item of readLabels(h)) {
        if (isRecord(item)) labels.set(String(item.name), item.applied_by);
    }
    for (const name of sorted(managed)) {
        if (!labels.has(name)) h.error(`${LABELS} lacks ${quote(name)}, which ${SPEC_CHANGES} declares; add the row.`);
    }
    for (const [name, applier] of labels) {
        if (!name.startsWith("spec/")) continue;
        if (!managed.has(name)) {
            h.error(
                `${LABELS}: ${quote(name)} is not a label ${SPEC_CHANGES} declares; remove it or teach the script.`,
            );
        } else if (applier !== "workflow") {
            h.error(`${LABELS}: the managed label ${quote(name)} must say applied_by workflow.`);
        }
    }
    // The labels workflow applies nothing the script did not plan, so its own literal allow-list has to be the
    // same set the script declares; a label added to one and not the other would be applied blindly or dropped.
    const allowed = new Set(
        [...labelsCaseLine(h.yaml(SPEC_LABELS_WORKFLOW)).matchAll(/spec\/[a-z-]+/g)].map((m) => m[0]),
    );
    if (!setEquals(allowed, managed)) {
        h.error(
            `${SPEC_LABELS_WORKFLOW} admits ${quoteList(sorted(allowed))}, ` +
                `${SPEC_CHANGES} declares ${quoteList(sorted(managed))}; make the two lists the same.`,
        );
    }
}

